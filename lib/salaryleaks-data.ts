/** Escape sel CSV: bungkus tanda kutip bila berisi koma, kutip, atau baris baru. */
const cell = (v: string | number | null | undefined) => {
  const s = v == null ? '' : String(v);
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export interface SalaryIds {
  playerId: string;
  tmId: string;
  fotmobId: string;
}

export function salaryCsv(rows: { row: SalaryRow; ids: SalaryIds }[]): string {
  const lines = rows.map(({ row: r, ids }) =>
    [
      ids.playerId, ids.tmId, ids.fotmobId, r.name, r.country, r.fixedPerWeek, r.fixedPerYear, r.bonusPerYear, r.totalPerYear, r.status, r.signed,
      r.expiration, r.yearsRemaining, r.remaining, r.releaseClause, r.pos1, r.pos2, r.age, r.role, SALARY_SOURCE,
    ]
      .map(cell)
      .join(',')
  );
  return [SALARY_COLUMNS.join(','), ...lines].join('\n') + '\n';
}
